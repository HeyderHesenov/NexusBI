def _downgrade_fn(tree: ast.Module) -> ast.FunctionDef | ast.AsyncFunctionDef | None:
    return next(
        (
            n
            for n in tree.body
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name == "downgrade"
        ),
        None,
    )


def test_every_revision_defines_a_downgrade() -> None:
    """A `downgrade()` that was never written is a rollback that cannot happen.

    Deliberately weaker than "every downgrade reverses its upgrade" — one of them
    legitimately cannot (c6d7e8f9a0b1: Postgres has no DROP VALUE for an enum
    label). This insists only that a no-op is a decision someone wrote down.

    ⚠️ Three things this got wrong on the first attempt, each measured against a
    crafted stub rather than argued about:

    * The canonical unfinished migration is not a bare ``pass`` — it is the
      ``pass`` between Alembic's own ``# ###`` markers, which any "is there a
      comment?" test reads as explained. That stub is now excluded explicitly.
    * ``ast.get_source_segment`` stops at the function's ``end_col_offset``, so
      ``pass  # nothing to reverse`` loses its comment and a correctly documented
      no-op was flagged. The raw lines are read instead.
    * ``return`` and ``raise NotImplementedError`` are no-ops too, and
      ``async def downgrade`` is not an ``ast.FunctionDef``.
    """
    missing: list[str] = []
    for path in sorted(VERSIONS.glob("*.py")):
        source = path.read_text(encoding="utf-8")
        lines = source.splitlines()
        fn = _downgrade_fn(ast.parse(source))
        if fn is None:
            missing.append(f"{path.name}: no downgrade()")
            continue

        body = [n for n in fn.body if not (isinstance(n, ast.Expr) and isinstance(n.value, ast.Constant))]
        is_noop = all(
            isinstance(n, ast.Pass)
            or (isinstance(n, ast.Return) and n.value is None)
            or (isinstance(n, ast.Raise) and isinstance(n.exc, ast.Call)
                and getattr(n.exc.func, "id", "") == "NotImplementedError")
            for n in body
        )
        if not is_noop:
            continue

        # fn.lineno is 1-based and points at `def`; end_lineno covers the body.
        block = [
            line
            for line in lines[fn.lineno - 1 : fn.end_lineno or fn.lineno]
            if AUTOGEN_MARKER not in line and AUTOGEN_END not in line
        ]
        if not any("#" in line for line in block) and not ast.get_docstring(fn):
            missing.append(f"{path.name}: downgrade() does nothing, and does not say why")

    assert not missing, "\n".join(missing)


def _enum_names(node: ast.AST) -> set[str]:
    """Named enum types a migration body creates.

    `sa.Enum(..., name='x')` inside create_table or alter_column emits CREATE
    TYPE on Postgres. `create_type=False` says the caller is reusing a type
    somebody else owns, so it carries no obligation to drop it.
    """
    found: set[str] = set()
    for sub in ast.walk(node):
        if not isinstance(sub, ast.Call):
            continue
        # `sa.Enum` / `postgresql.ENUM` (Attribute) and a bare `Enum` from a
        # direct import (Name) — the convention here is the first, but a rule
        # that only understood it would go quiet on the day someone changes the
        # import style, which is the wrong way for a guard to fail.
        called = getattr(sub.func, "attr", None) or getattr(sub.func, "id", None)
        if called not in {"Enum", "ENUM"}:
            continue
        kwargs = {k.arg: k.value for k in sub.keywords}
        name = kwargs.get("name")
        if not isinstance(name, ast.Constant) or not isinstance(name.value, str):
            continue
        create = kwargs.get("create_type")
        if isinstance(create, ast.Constant) and create.value is False:
            continue
        found.add(name.value)
    return found


def test_every_created_enum_type_is_dropped_on_downgrade() -> None:
    """The defect the Postgres round-trip found, pinned as a CLASS.

    `sa.Enum(name='dbtype')` inside create_table emits CREATE TYPE on Postgres,
    but `op.drop_table('datasources')` takes a bare name with no metadata and
    leaves the type behind. Measured on a real Postgres probe: `downgrade base`
    then `upgrade head` failed with `type "dbtype" already exists`, i.e. a
    rollback made the database un-redeployable.

    ⚠️ The first version of this test asserted `"DROP TYPE IF EXISTS dbtype" in
    downgrade_source` for one hardcoded revision. Measured by mutation: commenting
    the statement out left the substring in the comment and ALL FOUR TESTS PASSED,
    and the SQLite round-trip cannot see the defect either — so the guard was
    decoration. It also would not have noticed the second migration to create an
    enum. Parsed, and over every revision, for both reasons.
    """
    offenders: list[str] = []
    for path in sorted(VERSIONS.glob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        up = next(
            (n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name == "upgrade"),
            None,
        )
        down = _downgrade_fn(tree)
        if up is None or down is None:
            continue
        for name in sorted(_enum_names(up) - _enum_names(down)):
            offenders.append(
                f"{path.name}: upgrade() creates enum type '{name}', downgrade() never drops it"
            )

    assert not offenders, (
        "\n".join(offenders)
        + "\n\nAdd `sa.Enum(..., name=...).drop(op.get_bind(), checkfirst=True)` to downgrade(). "
        "It carries the dialect check and the IF EXISTS itself — a hand-written "
        "`op.execute('DROP TYPE ...')` has to get both right and is a syntax error on SQLite."
    )
